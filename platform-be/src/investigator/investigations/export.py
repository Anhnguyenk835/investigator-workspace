"""An investigation as a document someone can read, share or print.

Every claim keeps its evidence: citations become numbered notes that point at a list of
the records at the end, with each record's source, author, time and link. The report says
what it is (AI-generated, not reviewed) so it cannot be mistaken for a conclusion."""

from __future__ import annotations

import html
from collections.abc import Iterable
from dataclasses import dataclass, field
from datetime import datetime

from investigator.connectors import EvidenceRecord
from investigator.directory import Directory
from investigator.investigations.annotations import Annotation
from investigator.investigations.models import Investigation

DISCLAIMER = (
    "Generated by AI from the connected sources it could read. It is a starting point for a "
    "person to check, not a conclusion. Check each claim against the records it cites."
)


@dataclass
class Block:
    kind: str  # "p", "ul", "quote", "table"
    text: str = ""
    items: list[str] = field(default_factory=list)
    rows: list[list[str]] = field(default_factory=list)  # first row is the header


@dataclass
class Section:
    title: str
    blocks: list[Block] = field(default_factory=list)


class Report:
    def __init__(
        self, title: str, meta: list[tuple[str, str]], sections: list[Section]
    ) -> None:
        self.title, self.meta, self.sections = title, meta, sections


def _title(question: str) -> str:
    line = question.strip().splitlines()[0] if question.strip() else "Investigation"
    return line if len(line) <= 120 else line[:117] + "..."


class _Notes:
    """Numbers records in the order they are first cited."""

    def __init__(self, evidence: Iterable[EvidenceRecord]) -> None:
        self.by_id = {e.id: e for e in evidence}
        self.order: list[str] = []

    def cite(self, ids: Iterable[str]) -> str:
        marks = []
        for i in ids:
            if i not in self.by_id:
                continue
            if i not in self.order:
                self.order.append(i)
            marks.append(f"[{self.order.index(i) + 1}]")
        return " " + "".join(marks) if marks else ""


def _when(value: datetime | None) -> str:
    return value.strftime("%Y-%m-%d %H:%M UTC") if value else "undated"


def _side(r: EvidenceRecord) -> str:
    if not r.author_side:
        return ""
    label = {
        "customer": "customer side",
        "internal": "our team",
        "third_party": "other party",
    }[r.author_side]
    return f" ({label}{', ' + r.author_role if r.author_role else ''})"


def build_report(
    inv: Investigation,
    annotations: list[Annotation],
    directory: Directory | None = None,
) -> Report:
    notes = _Notes(inv.evidence)
    by_target: dict[str, list[Annotation]] = {}
    for a in annotations:
        by_target.setdefault(a.target_id, []).append(a)

    def reviews(target: str) -> list[str]:
        out = []
        for a in by_target.get(target, []):
            verb = {"note": "Note", "reviewed": "Reviewed", "disputed": "Disputed"}[
                a.kind
            ]
            out.append(
                f"{verb} by {a.author} ({a.created_at:%Y-%m-%d})"
                + (f": {a.text}" if a.text else "")
            )
        return out

    scope = ""
    if directory:
        project = directory.project(inv.context.project_id)
        customer = directory.customer(
            inv.context.customer_id or (project.customer_id if project else None)
        )
        scope = ", ".join(x.name for x in (customer, project) if x)
    meta = [
        ("Question", inv.question.strip()),
        (
            "Status",
            inv.status.replace("_", " ")
            + (
                f" (waiting for {inv.awaiting.replace('_', ' ')})"
                if inv.awaiting
                else ""
            ),
        ),
        ("Owner", inv.owner or "not assigned"),
        ("Run", str(inv.run_no)),
        ("Created", _when(inv.created_at)),
        ("Last updated", _when(inv.updated_at)),
    ]
    if scope:
        meta.append(("Scope", scope))
    if inv.scope_note:
        meta.append(("How the scope was set", inv.scope_note))
    if inv.resolved_at:
        meta.append(
            ("Resolved", f"{_when(inv.resolved_at)} by {inv.resolved_by or 'unknown'}")
        )

    sections: list[Section] = [Section("Read this first", [Block("p", DISCLAIMER)])]
    if inv.summary:
        sections.append(Section("Summary", [Block("p", inv.summary)]))

    sections.append(
        Section(
            "Source coverage",
            [
                Block(
                    "table",
                    rows=[["Source", "Result", "Detail"]]
                    + [
                        [c.source, c.status.replace("_", " "), c.detail or ""]
                        for c in inv.coverage
                    ],
                )
            ]
            if inv.coverage
            else [Block("p", "No source was searched.")],
        )
    )

    finding_blocks: list[Block] = []
    for f in inv.findings:
        support = {
            "supported": "backed by its records",
            "partial": "only partly backed",
            "unsupported": "not backed by its records",
            "unchecked": "not checked",
        }[f.support_status]
        finding_blocks.append(
            Block(
                "p",
                f"{f.claim}{notes.cite(f.supporting_evidence_ids)}\n"
                f"Status: {f.status.replace('_', ' ')}. Basis: {f.reasoning_type}. Evidence: {support}.",
            )
        )
        quotes = [
            f'"{c.quote}"{notes.cite([c.evidence_id])}' for c in f.support if c.quote
        ]
        if quotes:
            finding_blocks.append(Block("ul", items=quotes))
        if f.contradicting_evidence_ids:
            finding_blocks.append(
                Block(
                    "p",
                    "Contradicting evidence:"
                    + notes.cite(f.contradicting_evidence_ids),
                )
            )
        if reviews(f.id):
            finding_blocks.append(Block("ul", items=reviews(f.id)))
    sections.append(
        Section(
            "Findings",
            finding_blocks
            or [Block("p", "No finding is supported by the evidence found.")],
        )
    )

    sections.append(
        Section(
            "Timeline",
            [
                Block(
                    "ul",
                    items=[
                        f"{_when(t.occurred_at)}{'' if t.timestamp_precision == 'exact' else ' (' + t.timestamp_precision.replace('_', ' ') + ')'} "
                        f"- {t.title}: {t.summary}{notes.cite(t.evidence_ids)}"
                        for t in inv.timeline
                    ],
                )
            ]
            if inv.timeline
            else [Block("p", "No dated events were found.")],
        )
    )

    commit_blocks = []
    for c in inv.commitments:
        commit_blocks.append(
            Block(
                "p",
                f"{c.description}{notes.cite(c.evidence_ids)}\nStatus: {c.status.replace('_', ' ')} "
                f"({c.basis}). Committed by: {c.committed_by or 'not stated'}. Owner: {c.owner or 'not confirmed'}. "
                f"Due: {c.due_date or 'not stated'}.",
            )
        )
        if reviews(c.id):
            commit_blocks.append(Block("ul", items=reviews(c.id)))
    sections.append(
        Section("Commitments", commit_blocks or [Block("p", "None found.")])
    )

    if inv.blockers:
        sections.append(
            Section(
                "Blockers and dependencies",
                [
                    Block(
                        "ul",
                        items=[
                            f"{b.description} ({b.kind.replace('_', ' ')}, {b.basis}){notes.cite(b.evidence_ids)}"
                            for b in inv.blockers
                        ],
                    )
                ],
            )
        )
    if inv.conflicts:
        sections.append(
            Section(
                "Contradictions (neither side chosen)",
                [
                    Block(
                        "ul",
                        items=[
                            f"A: {c.claim_a.text}{notes.cite(c.claim_a.evidence_ids)}  versus  B: {c.claim_b.text}{notes.cite(c.claim_b.evidence_ids)}. {c.why}"
                            for c in inv.conflicts
                        ],
                    )
                ],
            )
        )
    if inv.gaps:
        sections.append(
            Section(
                "Gaps",
                [
                    Block(
                        "ul",
                        items=[
                            f"{g.what_missing} Why it matters: {g.why_it_matters} Follow up: {g.follow_up}"
                            for g in inv.gaps
                        ],
                    )
                ],
            )
        )
    if inv.actions:
        sections.append(
            Section(
                "Suggested next steps",
                [
                    Block(
                        "ul",
                        items=[
                            f"{a.title} - {a.rationale} (owner: {a.owner or 'not confirmed'}, priority: {a.priority}){notes.cite(a.evidence_ids)}"
                            for a in inv.actions
                        ],
                    )
                ],
            )
        )

    flagged = [
        i
        for i in inv.validation.issues
        if not inv.validation.passed or i.severity == "warning"
    ]
    if flagged:
        sections.append(
            Section(
                "Checks flagged",
                [Block("ul", items=[f"{i.severity}: {i.detail}" for i in flagged])],
            )
        )
    if inv.reviewer_notes:
        sections.append(
            Section(
                "Reviewer instructions given to the investigation",
                [Block("ul", items=inv.reviewer_notes)],
            )
        )
    if inv.draft:
        sections.append(
            Section(
                f"Customer update ({inv.draft_status.replace('_', ' ')})",
                [Block("quote", inv.draft)]
                + (
                    [Block("ul", items=inv.draft_warnings)]
                    if inv.draft_warnings
                    else []
                ),
            )
        )

    anchored = {f.id for f in inv.findings} | {c.id for c in inv.commitments}
    general = [a for a in annotations if a.target_id not in anchored]
    if general:
        sections.append(
            Section(
                "Other review notes",
                [
                    Block(
                        "ul",
                        items=[
                            f"{a.kind} by {a.author} ({a.created_at:%Y-%m-%d}) on {a.target_id}: {a.text}"
                            for a in general
                        ],
                    )
                ],
            )
        )

    if notes.order:
        rows = [["#", "Record", "Source", "Author", "Time", "Link"]]
        for n, eid in enumerate(notes.order, 1):
            r = notes.by_id[eid]
            rows.append(
                [
                    str(n),
                    f"{r.title} ({r.id})",
                    r.source,
                    f"{r.author or 'unknown'}{_side(r)}",
                    _when(r.occurred_at),
                    r.url or "",
                ]
            )
        sections.append(Section("Evidence", [Block("table", rows=rows)]))
    return Report(_title(inv.question), meta, sections)


def to_markdown(report: Report) -> str:
    def cell(text: str) -> str:
        return text.replace("|", "\\|").replace("\n", " ")

    out = [f"# {report.title}", ""]
    out += [f"- **{k}:** {v}" for k, v in report.meta]
    for s in report.sections:
        out += ["", f"## {s.title}", ""]
        for b in s.blocks:
            if b.kind == "p":
                out += [b.text.replace("\n", "  \n"), ""]
            elif b.kind == "quote":
                out += ["> " + line for line in b.text.splitlines()] + [""]
            elif b.kind == "ul":
                out += [f"- {i}" for i in b.items] + [""]
            elif b.kind == "table" and b.rows:
                head, *body = b.rows
                out += [
                    "| " + " | ".join(cell(h) for h in head) + " |",
                    "|" + "---|" * len(head),
                ]
                out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in body] + [
                    ""
                ]
    return "\n".join(out).rstrip() + "\n"


CSS = """
body{font:15px/1.55 -apple-system,Segoe UI,Helvetica,Arial,sans-serif;color:#1c2127;max-width:860px;margin:2rem auto;padding:0 1rem}
h1{font-size:1.6rem;margin-bottom:.4rem} h2{font-size:1.1rem;margin:1.6rem 0 .4rem;border-bottom:1px solid #d3d8de;padding-bottom:.25rem}
dl{display:grid;grid-template-columns:11rem 1fr;gap:.2rem 1rem;font-size:.9rem} dt{color:#5f6b7c} dd{margin:0}
table{border-collapse:collapse;width:100%;font-size:.85rem} th,td{border:1px solid #d3d8de;padding:.35rem .5rem;text-align:left;vertical-align:top}
th{background:#f6f7f9} blockquote{border-left:3px solid #48aff0;margin:.5rem 0;padding:.25rem .8rem;background:#f6f7f9;white-space:pre-wrap}
.note{border:1px solid #d9822b;background:#fff7ee;padding:.6rem .8rem} @media print{body{margin:0}}
"""


def to_html(report: Report) -> str:
    e = html.escape
    parts = [
        f"<h1>{e(report.title)}</h1>",
        "<dl>"
        + "".join(f"<dt>{e(k)}</dt><dd>{e(v)}</dd>" for k, v in report.meta)
        + "</dl>",
    ]
    for s in report.sections:
        parts.append(f"<h2>{e(s.title)}</h2>")
        for b in s.blocks:
            klass = ' class="note"' if s.title == "Read this first" else ""
            if b.kind == "p":
                parts.append(f"<p{klass}>{e(b.text).replace(chr(10), '<br>')}</p>")
            elif b.kind == "quote":
                parts.append(f"<blockquote>{e(b.text)}</blockquote>")
            elif b.kind == "ul":
                parts.append(
                    "<ul>" + "".join(f"<li>{e(i)}</li>" for i in b.items) + "</ul>"
                )
            elif b.kind == "table" and b.rows:
                head, *body = b.rows

                def tc(c: str) -> str:
                    return (
                        f'<a href="{e(c)}" rel="noreferrer noopener">{e(c)}</a>'
                        if c.startswith(("http://", "https://"))
                        else e(c)
                    )

                parts.append(
                    "<table><thead><tr>"
                    + "".join(f"<th>{e(h)}</th>" for h in head)
                    + "</tr></thead><tbody>"
                    + "".join(
                        "<tr>" + "".join(f"<td>{tc(c)}</td>" for c in r) + "</tr>"
                        for r in body
                    )
                    + "</tbody></table>"
                )
    return (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>{e(report.title)}</title><style>{CSS}</style></head><body>{''.join(parts)}</body></html>"
    )
